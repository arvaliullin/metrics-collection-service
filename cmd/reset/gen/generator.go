package gen

import (
	"go/ast"
	"go/format"
	"go/token"
	"strings"

	"github.com/arvaliullin/metrics-collection-service/cmd/reset/scan"

	"golang.org/x/tools/go/packages"
)

// Generator генерирует содержимое .gen.go файлов.
type Generator interface {
	Generate(pkg *packages.Package, targets []*scan.Target) ([]byte, error)
}

// DefaultGenerator реализует Generator.
type DefaultGenerator struct{}

// Generate формирует содержимое файла <исходный_файл>.gen.go для пакета и списка структур.
func (DefaultGenerator) Generate(pkg *packages.Package, targets []*scan.Target) ([]byte, error) {
	pname := pkgName(pkg)
	decls := make([]ast.Decl, 0, len(targets))
	for _, t := range targets {
		decls = append(decls, buildResetMethodDecl(t, pkg))
	}
	f := &ast.File{
		Name:  &ast.Ident{Name: pname},
		Decls: decls,
	}
	var buf strings.Builder
	if err := format.Node(&buf, token.NewFileSet(), f); err != nil {
		return nil, err
	}
	header := generatedFileHeader(pname)
	return format.Source(append([]byte(header), []byte(buf.String())...))
}

func buildResetMethodDecl(t *scan.Target, pkg *packages.Package) ast.Decl {
	recv := receiverName(t.TypeName.Obj().Name())
	body := generateResetBody(recv, t.Struct, pkg.Types)
	return &ast.FuncDecl{
		Recv: &ast.FieldList{
			List: []*ast.Field{{
				Names: []*ast.Ident{{Name: recv}},
				Type:  &ast.StarExpr{X: &ast.Ident{Name: t.TypeName.Obj().Name()}},
			}},
		},
		Name: &ast.Ident{Name: "Reset"},
		Type: &ast.FuncType{Params: &ast.FieldList{}, Results: &ast.FieldList{}},
		Body: &ast.BlockStmt{List: body},
	}
}

func generatedFileHeader(pkgName string) string {
	return "// Code generated by reset. DO NOT EDIT.\n" +
		"//\n" +
		"// Generated by this command:\n" +
		"//\n" +
		GenHeaderCmd +
		"//\n" +
		"// Package " + pkgName + " is a generated reset package.\n"
}
